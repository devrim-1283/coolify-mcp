/** Descriptions longer than this are dropped whole. Context budget beats prose. */
const MAX_DESCRIPTION_CHARS = 200;

/** Summaries are search text and are shown per result row; keep them one line. */
const MAX_SUMMARY_CHARS = 160;

/**
 * Keys copied verbatim. An allowlist, not a denylist: a denylist silently leaks
 * whatever OpenAPI adds next, and the whole point of this pass is a bounded
 * payload. Includes vocabulary the current spec does not use yet, so a future
 * upstream constraint is preserved rather than dropped.
 */
const SCALAR_SCHEMA_KEYS: ReadonlySet<string> = new Set([
  'type',
  'format',
  'title',
  'description',
  'required',
  'nullable',
  'deprecated',
  'readOnly',
  'writeOnly',
  'minimum',
  'maximum',
  'exclusiveMinimum',
  'exclusiveMaximum',
  'multipleOf',
  'minLength',
  'maxLength',
  'pattern',
  'minItems',
  'maxItems',
  'uniqueItems',
  'minProperties',
  'maxProperties',
]);

/** Keys whose value is itself a schema (or an array of schemas). */
const NESTED_SCHEMA_KEYS: ReadonlySet<string> = new Set([
  'items',
  'additionalProperties',
  'not',
  'oneOf',
  'anyOf',
  'allOf',
]);

/** Keys whose value is a map of property name -> schema. */
const SCHEMA_MAP_KEYS: ReadonlySet<string> = new Set(['properties', 'patternProperties']);

/**
 * Keys holding instance data rather than schemas. Copied untouched — running the
 * key allowlist over a `default: { ... }` value would mangle real data.
 */
const OPAQUE_SCHEMA_KEYS: ReadonlySet<string> = new Set(['default', 'const', 'enum']);

