/**
 * Build-time catalog generator: Coolify's OpenAPI spec -> src/generated/*.
 *
 * Run with `npm run codegen`. The catalog is committed rather than fetched at
 * runtime because every MCP client spawns this process fresh: a 795 KB parse
 * per start, a network dependency for a tool that often runs against an offline
 * homelab, and a non-deterministic npm tarball are each worse than a file in
 * git. CI re-runs this and diffs the result, so upstream drift breaks the build
 * loudly instead of shipping a stale surface silently.
 */

