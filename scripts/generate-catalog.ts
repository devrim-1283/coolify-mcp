function assertRoutesMatched(
  label: string,
  declared: readonly string[],
  present: ReadonlySet<string>,
): void {
  const missing = declared.filter((route) => !present.has(route));
  if (missing.length > 0) {
    fail(
      `${label} lists ${missing.length} route(s) that no longer exist: ${missing.join(', ')}.\n` +
        'Either upstream moved them or the spec is wrong. Do not delete the entry to make ' +
        'this pass — find where the operation went first.',
    );
  }
}

function syntheticOperation(method: HttpMethod, path: string, op: OpenApiOperation): RawOperation {
  return { id: 'synthetic', method, path, route: `${method} ${path}`, op };
}

/**
 * The stub detector strips nothing from the current spec — this revision simply
 * does not document the `post_required` GETs. That leaves the single most
 * safety-critical rule in this generator as unexercised code, free to rot until
 * an upstream release brings the stubs back and a GET that restarts an
 * application lands in a tool annotated `readOnlyHint: true`. So it is proved
 * against synthetic stubs on every run, one case per rule, plus a control that
 * must survive.
 */
function assertStubDetectorWorks(): void {
  const stubs: ReadonlyArray<readonly [string, RawOperation]> = [
    [
      'GET on an action route that documents a 200',
      syntheticOperation('GET', '/applications/{uuid}/restart', {
        summary: 'Restart',
        responses: { '200': {} },
      }),
    ],
    [
      'operation with no success response',
      syntheticOperation('GET', '/servers/{uuid}/anything', {
        responses: { '404': {}, '405': {} },
      }),
    ],
    [
      'operation whose description names post_required',
      syntheticOperation('GET', '/servers/{uuid}/anything', {
        description: 'See OtherController@post_required.',
        responses: { '200': {} },
      }),
    ],
  ];
  for (const [label, raw] of stubs) {
    if (stubReason(raw) === undefined) {
      fail(`the post_required stub detector no longer catches: ${label}`);
    }
  }

  const real = syntheticOperation('GET', '/applications', {
    summary: 'List',
    responses: { '200': {}, '401': {} },
  });
  const reason = stubReason(real);
  if (reason !== undefined) fail(`the stub detector strips real operations: ${reason}`);
}

function assertCatalogInvariants(rows: readonly CatalogOperation[]): void {
  const seen = new Set<string>();
  for (const row of rows) {
    if (seen.has(row.id)) fail(`duplicate operation id: ${row.id}`);
    seen.add(row.id);
    if (row.danger === 'safe' && row.method !== 'GET') {
      fail(`${row.id} is classified safe but is a ${row.method}`);
    }
    if (row.danger === 'destructive' && row.method === 'GET') {
      fail(`${row.id} is classified destructive but is a GET`);
    }
  }
  if (rows.length === 0) fail('catalog is empty');
}

function assertSchemaCoverage(
  rows: readonly CatalogOperation[],
  schemas: Record<string, unknown>,
): void {
  const withBody = new Set(rows.filter((r) => r.hasBody).map((r) => r.id));
  const emitted = new Set(Object.keys(schemas));
  const missing = [...withBody].filter((id) => !emitted.has(id));
  const extra = [...emitted].filter((id) => !withBody.has(id));
  if (missing.length > 0) fail(`hasBody without a schema: ${missing.join(', ')}`);
  if (extra.length > 0) fail(`schema without a catalog row: ${extra.join(', ')}`);
}

