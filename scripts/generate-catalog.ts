const SCRIPT_DIR = fileURLToPath(new URL('.', import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, '..');
const SPEC_PATH = join(SCRIPT_DIR, 'coolify-openapi.json');
const OUT_DIR = join(REPO_ROOT, 'src', 'generated');

const BANNER = [
  '// GENERATED FILE — DO NOT EDIT, run npm run codegen',
  `// Source: scripts/coolify-openapi.json (Coolify ${COOLIFY_VERSION})`,
  '',
].join('\n');

const METHOD_ORDER: readonly HttpMethod[] = ['GET', 'POST', 'PATCH', 'PUT', 'DELETE'];

// ---------------------------------------------------------------------------
// Minimal spec shape — only the parts this generator reads
// ---------------------------------------------------------------------------

interface OpenApiParameter {
  name?: string;
  in?: string;
}

interface OpenApiOperation {
  operationId?: string;
  summary?: string;
  description?: string;
  parameters?: OpenApiParameter[];
  requestBody?: { content?: Record<string, { schema?: unknown } | undefined> };
  responses?: Record<string, unknown>;
}

interface OpenApiSpec {
  paths?: Record<string, Record<string, OpenApiOperation> | undefined>;
  components?: Record<string, unknown>;
}

interface RawOperation {
  id: string;
  method: HttpMethod;
  path: string;
  route: string;
  op: OpenApiOperation;
}

function fail(message: string): never {
  process.stderr.write(`\ncodegen FAILED: ${message}\n\n`);
  process.exit(1);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

// ---------------------------------------------------------------------------
// Collection
// ---------------------------------------------------------------------------

function collectRawOperations(spec: OpenApiSpec): RawOperation[] {
  const collected: RawOperation[] = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const [verb, op] of Object.entries(item ?? {})) {
      const method = METHOD_ORDER.find((m) => m === verb.toUpperCase());
      if (method === undefined) continue;
      const id = op.operationId?.trim();
      if (!id) fail(`${verb.toUpperCase()} ${path} has no operationId — it cannot be addressed.`);
      collected.push({ id, method, path, route: `${method} ${path}`, op });
    }
  }
  return collected;
}

/** Returns why this operation is a stub, or undefined when it is real. */
function stubReason(raw: RawOperation): string | undefined {
  const text = `${raw.op.summary ?? ''} ${raw.op.description ?? ''} ${raw.id}`;
  if (POST_REQUIRED_TEXT.test(text)) return 'post_required text';

  const codes = Object.keys(raw.op.responses ?? {});
  const hasSuccess = codes.some((code) => /^[23]\d\d$/.test(code) || code === 'default');
  if (!hasSuccess) return `no success response (${codes.join(',') || 'none'})`;

  // A GET that Coolify answers with "use POST" may still document a 200 for the
  // error envelope, so the response check alone is not enough.
  const segments = raw.path.split('/').filter(Boolean);
  const last = segments[segments.length - 1];
  if (raw.method === 'GET' && last !== undefined && ACTION_SEGMENTS.has(last)) {
    return `GET on action route /${last}`;
  }
  return undefined;
}

// ---------------------------------------------------------------------------
// Classification
// ---------------------------------------------------------------------------

function classifyDanger(raw: RawOperation, overrides: ReadonlySet<string>): DangerClass {
  if (raw.method === 'DELETE' || overrides.has(raw.route)) return 'destructive';
  if (raw.method === 'GET') return 'safe';
  return 'write';
}

function familyFor(path: string): OperationFamily {
  const segment = path.split('/').find((s) => s.length > 0 && !s.startsWith('{'));
  if (segment === undefined) return 'other';
  return FAMILY_BY_SEGMENT[segment] ?? 'other';
}

function firstSentence(text: string): string {
  const match = /^[\s\S]*?[.!?](?=\s|$)/.exec(text.trim());
  return (match?.[0] ?? text).trim();
}

function truncate(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max - 1).trimEnd()}…`;
}

/**
 * The spec's `summary` is a UI label — "List", "Get", "Start" — which is close
 * to worthless as search text once it is separated from the sidebar heading it
 * was written under. `description` is the sentence that actually names the
 * resource, so it wins.
 */
function summaryFor(raw: RawOperation): string {
  const description = firstSentence(raw.op.description ?? '');
  const summary = (raw.op.summary ?? '').trim();
  return truncate(description || summary || raw.id, MAX_SUMMARY_CHARS);
}

function pathParamsOf(path: string): string[] {
  return [...path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1] ?? '');
}

function queryParamsOf(raw: RawOperation): string[] {
  const names: string[] = [];
  for (const parameter of raw.op.parameters ?? []) {
    const { name } = parameter;
    if (parameter.in === 'query' && typeof name === 'string' && name.length > 0) names.push(name);
  }
  return names;
}

function toCatalogOperation(
  raw: RawOperation,
  overrides: ReadonlySet<string>,
  costly: ReadonlySet<string>,
): CatalogOperation {
  const row: CatalogOperation = {
    id: raw.id,
    method: raw.method,
    path: raw.path,
    family: familyFor(raw.path),
    summary: summaryFor(raw),
    // Taken from the URL template, not from `parameters`: the template is what
    // the HTTP client must actually substitute, and specs under-declare.
    pathParams: pathParamsOf(raw.path),
    queryParams: queryParamsOf(raw),
    // Derived from the same lookup that emits the schema, so `hasBody === true`
    // and "getSchema(id) returns something" can never disagree.
    hasBody: bodySchemaOf(raw) !== undefined,
    danger: classifyDanger(raw, overrides),
  };
  if (costly.has(raw.route)) row.costly = true;
  return row;
}

// ---------------------------------------------------------------------------
// Request body schemas
// ---------------------------------------------------------------------------

function bodySchemaOf(raw: RawOperation): unknown {
  return raw.op.requestBody?.content?.['application/json']?.schema;
}

function resolveRef(spec: OpenApiSpec, ref: string): unknown {
  if (!ref.startsWith('#/')) fail(`external $ref is not supported: ${ref}`);
  let node: unknown = spec;
  for (const segment of ref.slice(2).split('/')) {
    if (!isRecord(node)) fail(`unresolvable $ref: ${ref}`);
    node = node[segment.replace(/~1/g, '/').replace(/~0/g, '~')];
  }
  if (node === undefined) fail(`unresolvable $ref: ${ref}`);
  return node;
}

function dereference(node: unknown, spec: OpenApiSpec, seen: ReadonlySet<string>): unknown {
  if (Array.isArray(node)) return node.map((child) => dereference(child, spec, seen));
  if (!isRecord(node)) return node;

  const ref = node['$ref'];
  if (typeof ref === 'string') {
    // A self-referential schema cannot be inlined. `type: object` is a truthful
    // stand-in here because the generic execute path passes bodies through
    // without validating them anyway.
    if (seen.has(ref)) return { type: 'object' };
    return dereference(resolveRef(spec, ref), spec, new Set([...seen, ref]));
  }

  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) out[key] = dereference(value, spec, seen);
  return out;
}

function pruneSchema(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(pruneSchema);
  if (!isRecord(node)) return node;

  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) {
    if (SCHEMA_MAP_KEYS.has(key)) {
      out[key] = pruneSchemaMap(value);
    } else if (NESTED_SCHEMA_KEYS.has(key)) {
      out[key] = pruneSchema(value);
    } else if (OPAQUE_SCHEMA_KEYS.has(key)) {
      out[key] = value;
    } else if (key === 'description') {
      if (typeof value === 'string' && value.length <= MAX_DESCRIPTION_CHARS) out[key] = value;
    } else if (SCALAR_SCHEMA_KEYS.has(key)) {
      out[key] = value;
    }
    // Everything else — `example`, `examples`, vendor extensions — is dropped.
  }
  return out;
}

/** Property names are data, so only the values run through the key allowlist. */
function pruneSchemaMap(node: unknown): unknown {
  if (!isRecord(node)) return pruneSchema(node);
  const out: Record<string, unknown> = {};
  for (const [name, schema] of Object.entries(node)) out[name] = pruneSchema(schema);
  return out;
}

function buildSchemas(spec: OpenApiSpec, kept: readonly RawOperation[]): Record<string, unknown> {
  const schemas: Record<string, unknown> = {};
  for (const raw of kept) {
    const schema = bodySchemaOf(raw);
    if (schema === undefined) continue;
    schemas[raw.id] = pruneSchema(dereference(schema, spec, new Set()));
  }
  return schemas;
}

// ---------------------------------------------------------------------------
// Rendering — output is prettier-shaped so `format:check` stays green
// ---------------------------------------------------------------------------

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Column budget for keeping an array on one line. Matches prettier's default. */
const INLINE_WIDTH = 72;

function renderString(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r');
  return `'${escaped}'`;
}

/**
 * Objects always expand and arrays collapse when they fit. That is prettier's
 * own shape, which keeps `format:check` from fighting the generator, and it
 * happens to be the readable choice: one field per line diffs cleanly, while
 * `pathParams: ['uuid']` on its own three lines would not.
 */
function renderValue(value: unknown, indent: string): string {
  if (typeof value === 'string') return renderString(value);
  if (typeof value === 'number' || typeof value === 'boolean' || value === null) {
    return String(value);
  }

  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const parts = value.map((item) => renderValue(item, inner));
    const inline = `[${parts.join(', ')}]`;
    if (!inline.includes('\n') && indent.length + inline.length <= INLINE_WIDTH) return inline;
    return `[\n${parts.map((part) => `${inner}${part},`).join('\n')}\n${indent}]`;
  }

  if (isRecord(value)) {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    if (entries.length === 0) return '{}';
    const lines = entries.map(([key, v]) => {
      const renderedKey = IDENTIFIER.test(key) ? key : renderString(key);
      return `${inner}${renderedKey}: ${renderValue(v, inner)},`;
    });
    return `{\n${lines.join('\n')}\n${indent}}`;
  }

  return 'null';
}

function renderCatalog(rows: readonly CatalogOperation[]): string {
  return [
    BANNER,
    "import type { CatalogOperation } from '../types.js';",
    '',
    `export const CATALOG: CatalogOperation[] = ${renderValue(rows, '')};`,
    '',
  ].join('\n');
}

function renderSchemas(schemas: Record<string, unknown>): string {
  return [
    BANNER,
    '/**',
    ' * Dereferenced, pruned request-body schemas keyed by operation id.',
    ' * Absent id means the operation takes no JSON body.',
    ' */',
    `export const SCHEMAS: Record<string, unknown> = ${renderValue(schemas, '')};`,
    '',
  ].join('\n');
}

function renderMeta(meta: CatalogMeta): string {
  return [
    BANNER,
    "import type { CatalogMeta } from '../types.js';",
    '',
    `export const METADATA: CatalogMeta = ${renderValue(meta, '')};`,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Deterministic timestamp
// ---------------------------------------------------------------------------

const GENERATED_AT_PLACEHOLDER = '__GENERATED_AT__';

function readIfExists(path: string): string | undefined {
  return existsSync(path) ? readFileSync(path, 'utf8') : undefined;
}

/** Git may have handed us CRLF on checkout; that is not a content change. */
function sameContent(a: string | undefined, b: string): boolean {
  return a !== undefined && a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');
}

/**
 * `generatedAt` would otherwise dirty the tree on every run, and CI runs
 * `npm run codegen && git diff --exit-code`. So the stamp only moves when the
 * emitted content moves: re-running against an unchanged spec is a no-op.
 */
function resolveGeneratedAt(previousMeta: string | undefined, template: string): string {
  const now = new Date().toISOString();
  if (previousMeta === undefined) return now;
  const previousStamp = /generatedAt: '([^']*)'/.exec(previousMeta)?.[1];
  if (previousStamp === undefined) return now;
  const replayed = template.replace(
    renderString(GENERATED_AT_PLACEHOLDER),
    renderString(previousStamp),
  );
  return sameContent(previousMeta, replayed) ? previousStamp : now;
}

