// Pinned expectations — the tripwires
// ---------------------------------------------------------------------------

/**
 * Operations in the vendored spec. Asserted, not measured: a generator that
 * quietly adapts to whatever it is fed will happily emit a half-catalog after a
 * bad spec refresh. Bump this deliberately, in the same commit as the new spec.
 */
const EXPECTED_RAW_OPERATIONS = 189;

/**
 * The spec's own `info.version` is the constant "0.1" and carries no
 * information. This is the coollabsio/coolify release the spec was taken from.
 */
const COOLIFY_VERSION = '4.2.0';

/**
 * Hand-maintained. These are not DELETEs, so the "gate the DELETEs" rule misses
 * them, yet they switch the API off — from the token's own point of view that
 * is irreversible, because the call that would switch it back on is itself
 * behind the API that just went away.
 *
 * Keyed by route rather than operationId: the route is the semantic identity,
 * while the id is generated by upstream tooling and can be renamed. Every entry
 * must match exactly one operation or the generator fails.
 */
const DESTRUCTIVE_OVERRIDE_ROUTES: readonly string[] = ['POST /disable', 'POST /mcp/disable'];

/**
 * Provisions billable cloud infrastructure. Not gated — the brief keeps
 * everything non-destructive open — but surfaced in search results so the model
 * sees the consequence before it calls.
 */
const COSTLY_ROUTES: readonly string[] = [
  'POST /servers/hetzner',
  'POST /servers/digitalocean',
  'POST /servers/vultr',
];

// ---------------------------------------------------------------------------
// Stub stripping
// ---------------------------------------------------------------------------

/**
 * Coolify registers GET routes that reach `OtherController@post_required` and
 * return nothing but "use POST". If one enters the catalog, a search for
 * "restart application" returns a GET — which the tool layer is entitled to
 * annotate `readOnlyHint: true` — that actually restarts the application.
 *
 * Detected by pattern, never by a hardcoded path list, so the defence survives
 * upstream adding or moving such routes.
 */
const POST_REQUIRED_TEXT = /post_required/i;

/**
 * Last path segments that name a state change. A GET here is a stub by
 * construction: Coolify exposes none of these as readable resources, so there
 * is no legitimate operation to lose.
 */
const ACTION_SEGMENTS: ReadonlySet<string> = new Set([
  'start',
  'stop',
  'restart',
  'deploy',
  'enable',
  'disable',
  'validate',
  'cancel',
]);

// ---------------------------------------------------------------------------
// Families
// ---------------------------------------------------------------------------

/**
 * First non-parameter path segment -> family. Segments absent here fall back to
 * `other`; that is deliberate rather than fatal, because the raw-count assertion
 * already forces a human to look whenever upstream adds routes.
 */
const FAMILY_BY_SEGMENT: Readonly<Record<string, OperationFamily>> = {
  applications: 'applications',
  databases: 'databases',
  services: 'services',
  servers: 'servers',
  projects: 'projects',
  deployments: 'deployments',
  // POST /deploy triggers a deployment; filing it anywhere else splits the one
  // concept a user searches for across two families.
  deploy: 'deployments',
  teams: 'teams',
  security: 'security',
  destinations: 'destinations',
  'github-apps': 'github-apps',
  'cloud-tokens': 'cloud-tokens',
  hetzner: 'hetzner',
  digitalocean: 'digitalocean',
  vultr: 'vultr',
  tags: 'tags',
};

// ---------------------------------------------------------------------------
// Schema pruning
