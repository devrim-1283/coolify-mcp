import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import type {
  CatalogMeta,
  CatalogOperation,
  DangerClass,
  HttpMethod,
  OperationFamily,
} from '../src/types.js';

